import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import test from 'node:test';
const script=readFileSync(resolve('scripts/word-preview-browser-smoke.mjs'),'utf8');
const fixture=readFileSync(resolve('scripts/fixtures/word-preview/main.tsx'),'utf8');
test('Word acceptance reuses lifecycle and official context routing before page creation',()=>{
  assert.match(script,/from '\.\/browser-smoke-harness\.mjs'/);
  assert.match(script,/from 'playwright-core'/);
  assert.match(script,/startBrowser\(\{chromePath:chrome,viewport:\{width:1280,height:1000,mobile:false\}/);
  assert.doesNotMatch(script,/class CdpClient|--no-sandbox|--disable-web-security|Target.setAutoAttach|Fetch.enable|for\(;;\)/);
  assert.ok(script.indexOf("await context.route('**/*'")<script.indexOf('await context.newPage()'));
  assert.match(script,/serviceWorkers:'block'/);
  assert.ok(script.indexOf("await page.setContent('")<script.indexOf('await page.goto('));
  assert.match(script,/verifyPinnedPlaywrightSwSource\(\)/);
  assert.match(script,/navigator.serviceWorker.register\('\/__word_probe__\/worker.js'\)/);
  assert.match(script,/pageErrors.filter\(error=>!isPinnedPlaywrightSwError\(error\)\)/);
  assert.match(script,/route.abort\('blockedbyclient'\)/);
  assert.match(script,/nested-control/);
  assert.match(script,/assert.deepEqual\(requestLog,\[\]/);
  assert.match(script,/context\?\.close\(\)/);
  assert.match(script,/lifecycle\?\.close\(\)/);
  assert.match(script,/server\?\.close\(\)/);
  assert.match(script,/word_preview_cleanup_failed/);
  assert.match(fixture,/import WordPreview from/);
  assert.match(fixture,/styles\/tailwind.css/);
  assert.match(fixture,/createSyntheticWordDocument\(\{landscape,fallback\}\)/);
  assert.doesNotMatch(fixture,/Content-Security-Policy|prepareWordPreviewDocument|<iframe/);
});
test('controlled Close observes real converter settlement without altering outputs',()=>{
  const observer=readFileSync(resolve('scripts/fixtures/word-preview/conversion-observer.mjs'),'utf8');
  assert.match(observer,/return await convert\(input\)/);
  assert.match(observer,/finally/);
  assert.match(script,/gate|__wordSmokeGate/);
  assert.ok(script.indexOf("await page.locator('#close').click()")<script.indexOf('window.__wordSmokeGate.release()'));
  const production=readFileSync(resolve('src/components/documents/previews/WordPreview.tsx'),'utf8');
  assert.doesNotMatch(production,/observeWordConversion|__wordSmokeGate/);
});
