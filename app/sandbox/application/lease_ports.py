"""Application-owned capabilities for Sandbox lease lifecycle persistence."""

from typing import Any, Protocol


class SandboxRuntimeLeasePort(Protocol):
    """Persist the runtime-owned lease around provider dispatch."""

    def new_lease_id(self) -> str: ...

    async def create_sandbox_lease(self, conn: Any, **kwargs: Any) -> dict[str, Any]: ...

    async def fence_sandbox_lease_release(self, conn: Any, **kwargs: Any) -> Any: ...

    async def record_sandbox_executor_accepted(self, conn: Any, **kwargs: Any) -> dict[str, Any] | None: ...


class SandboxExecutorCallbackLeasePort(Protocol):
    """Record a callback against its exact current runtime lease."""

    async def record_sandbox_executor_terminal(self, conn: Any, **kwargs: Any) -> Any: ...

    async def record_sandbox_executor_heartbeat(self, conn: Any, **kwargs: Any) -> dict[str, Any] | None: ...

    async def record_opensandbox_renewal_receipt(self, conn: Any, **kwargs: Any) -> dict[str, Any] | None: ...


class SandboxLeaseTransportPort(Protocol):
    """Operate user and administrator lease endpoints within caller transactions."""

    async def create_sandbox_lease(self, conn: Any, **kwargs: Any) -> dict[str, Any]: ...

    async def get_sandbox_lease(self, conn: Any, **kwargs: Any) -> dict[str, Any] | None: ...

    async def renew_sandbox_lease(self, conn: Any, **kwargs: Any) -> dict[str, Any] | None: ...

    async def release_sandbox_lease(self, conn: Any, **kwargs: Any) -> dict[str, Any] | None: ...

    async def list_sandbox_leases(self, conn: Any, **kwargs: Any) -> list[dict[str, Any]]: ...

    async def get_sandbox_executor_reconciliation_summary(self, conn: Any, **kwargs: Any) -> dict[str, Any]: ...

    async def record_sandbox_runtime_cleanup_outcome(self, conn: Any, **kwargs: Any) -> None: ...


class SandboxExecutorReconciliationPort(Protocol):
    """Claim and settle durable executor receipts without owning provider I/O."""

    async def release_sandbox_executor_probe_claim(self, conn: Any, **kwargs: Any) -> Any: ...

    async def retry_sandbox_executor_reconciliation(self, conn: Any, **kwargs: Any) -> Any: ...

    async def has_sandbox_executor_reconciliation_claim(self, conn: Any, **kwargs: Any) -> bool: ...

    async def quarantine_sandbox_executor_reconciliation(self, conn: Any, **kwargs: Any) -> Any: ...

    async def mark_sandbox_executor_reconciliation_cleanup_pending(self, conn: Any, **kwargs: Any) -> Any: ...

    async def record_sandbox_executor_terminal_diagnostics(self, conn: Any, **kwargs: Any) -> Any: ...

    async def record_sandbox_executor_terminal(self, conn: Any, **kwargs: Any) -> Any: ...

    async def claim_sandbox_executor_suspects(self, conn: Any, **kwargs: Any) -> list[dict[str, Any]]: ...

    async def claim_sandbox_executor_reconciliations(self, conn: Any, **kwargs: Any) -> list[dict[str, Any]]: ...

    async def next_sandbox_executor_reconciliation_retry_delay(self, conn: Any) -> float | None: ...


class SandboxRunLeaseReader(Protocol):
    """Read the Sandbox-owned leases included in a Runs admin projection."""

    async def list_sandbox_leases_for_run(
        self, conn: Any, *, tenant_id: str, run_id: str
    ) -> list[dict[str, Any]]: ...

